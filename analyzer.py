
import cv2  # OpenCV — бібліотека для роботи з відео та зображеннями
import json  # Бібліотека для роботи з JSON (збереження результатів)
import mediapipe as mp  # MediaPipe — бібліотека для розпізнавання тіла людини
from pathlib import Path  # Допомагає правильно працювати зі шляхами до файлів


# Отримуємо доступ до модуля Pose бібліотеки MediaPipe.
# Pose — це готова модель, яка визначає 33 ключові точки тіла людини.
# Наприклад: плечі, лікті, зап'ястя, коліна, стопи тощо.
mp_pose = mp.solutions.pose


def analyze_video(video_path):
    """
    Основна функція нашого аналізатора.

    Приймає:
        video_path — шлях до відеофайлу.

    Повертає:
        Python-словник (dict), який містить:
        - інформацію про відео;
        - координати 33 точок для кожного кадру;
        - номери кадрів і часові позначки.

    Саме цей словник у майбутньому зможе отримувати
    бекенд Адріана для передачі на фронтенд Юри.
    """

    # Відкриваємо відео за допомогою OpenCV.
    # VideoCapture створює об'єкт, який дозволяє читати
    # відео послідовно, кадр за кадром.
    #
    # str(video_path) перетворює шлях на звичайний рядок,
    # оскільки video_path може бути об'єктом Path.
    cap = cv2.VideoCapture(str(video_path))

    # Перевіряємо, чи вдалося відкрити відео.
    # isOpened() повертає True, якщо відео відкрилося,
    # і False, якщо файл відсутній або формат не підтримується.
    if not cap.isOpened():
        raise FileNotFoundError(
            f"Не вдалося відкрити відео: {video_path}"
        )

    # Отримуємо кількість кадрів за секунду (FPS).
    # Наприклад, якщо fps = 60, то відео містить
    # приблизно 60 кадрів на кожну секунду.
    #
    # FPS потрібен, щоб визначити момент часу,
    # якому відповідає кожен кадр.
    fps = cap.get(cv2.CAP_PROP_FPS)

    # Створюємо порожній список.
    # У нього будемо додавати інформацію про кожен кадр.
    #
    # Наприклад:
    # frames = [кадр_0, кадр_1, кадр_2, ...]
    frames = []

    # Лічильник кадрів.
    # Починаємо з нуля, оскільки в програмуванні
    # індексація зазвичай починається з 0.
    frame_index = 0

    try:
        # Створюємо модель MediaPipe Pose.
        #
        # static_image_mode=False:
        # Повідомляємо, що обробляємо відео, а не окремі фото.
        # MediaPipe може відстежувати людину між кадрами,
        # не запускаючи повне виявлення на кожному кадрі.
        #
        # min_detection_confidence=0.5:
        # Мінімальний поріг впевненості моделі
        # під час початкового виявлення людини.
        #
        # min_tracking_confidence=0.5:
        # Мінімальний поріг впевненості під час
        # відстеження пози між кадрами.
        #
        # as pose:
        # Зберігаємо створену модель у змінну pose.
        #
        # with автоматично звільнить ресурси моделі
        # після завершення роботи цього блоку.
        with mp_pose.Pose(
            static_image_mode=False,
            min_detection_confidence=0.5,
            min_tracking_confidence=0.5
        ) as pose:

            # Цикл працює, поки ми можемо отримувати
            # наступні кадри з відеофайлу.
            while True:

                # Зчитуємо наступний кадр.
                #
                # ret — логічна змінна (True або False).
                # True означає, що кадр отримано успішно.
                #
                # frame — матриця пікселів зображення.
                # Наприклад, кольоровий кадр має форму:
                # висота × ширина × 3 кольорові канали.
                ret, frame = cap.read()

                # Якщо кадр не вдалося прочитати,
                # завершуємо цикл.
                #
                # Зазвичай це відбувається,
                # коли відео закінчилося.
                if not ret:
                    break

                # OpenCV зазвичай представляє кольори
                # у форматі BGR (Blue, Green, Red).
                #
                # MediaPipe Pose очікує RGB
                # (Red, Green, Blue).
                #
                # cvtColor переставляє кольорові канали.
                image_rgb = cv2.cvtColor(
                    frame,
                    cv2.COLOR_BGR2RGB
                )

                # Передаємо підготовлений кадр у нейромережу.
                #
                # pose.process() аналізує зображення
                # і повертає об'єкт results.
                #
                # У results.pose_landmarks містяться
                # координати точок тіла, якщо позу знайдено.
                results = pose.process(image_rgb)

                # Створюємо словник для поточного кадру.
                #
                # frame_index — порядковий номер кадру.
                #
                # timestamp_sec — час кадру в секундах.
                # Наприклад, для FPS = 60:
                # кадр 0  -> 0.000 секунди
                # кадр 30 -> 0.500 секунди
                # кадр 60 -> 1.000 секунди
                #
                # fps > 0 — перевірка, щоб не ділити на нуль.
                #
                # landmarks = None означає, що поки
                # координат для цього кадру немає.
                frame_data = {
                    "frame_index": frame_index,
                    "timestamp_sec": (
                        round(frame_index / fps, 3)
                        if fps > 0 else None
                    ),
                    "landmarks": None
                }

                # Перевіряємо, чи MediaPipe знайшов
                # позу людини на поточному кадрі.
                #
                # Якщо позу не знайдено, landmarks залишиться None.
                # Це важливо для Юри, щоб він не намагався
                # малювати неіснуючий скелет.
                if results.pose_landmarks:

                    # Створюємо словник для координат
                    # усіх точок тіла.
                    landmarks = {}

                    # mp_pose.PoseLandmark — перелік
                    # усіх 33 ключових точок людини.
                    #
                    # Цикл for перебирає їх по черзі:
                    # NOSE, LEFT_EYE_INNER, LEFT_EYE...
                    # RIGHT_SHOULDER, RIGHT_ELBOW тощо.
                    for point in mp_pose.PoseLandmark:

                        # point.value — числовий індекс точки.
                        #
                        # Наприклад:
                        # RIGHT_SHOULDER = 12
                        # RIGHT_ELBOW = 14
                        # RIGHT_WRIST = 16
                        #
                        # За індексом отримуємо об'єкт,
                        # який містить координати цієї точки.
                        landmark = (
                            results.pose_landmarks.landmark[point.value]
                        )

                        # Додаємо координати точки до словника.
                        #
                        # point.name.lower():
                        # Перетворюємо назву на маленькі літери.
                        # RIGHT_ELBOW -> right_elbow
                        #
                        # x — горизонтальна координата.
                        # 0 означає лівий край кадру,
                        # 1 означає правий край кадру.
                        #
                        # y — вертикальна координата.
                        # 0 означає верхній край,
                        # 1 означає нижній край кадру.
                        #
                        # z — відносна глибина точки.
                        # Це НЕ точна відстань у метрах.
                        #
                        # visibility — оцінка ймовірності
                        # того, що точка видима на зображенні.
                        # Ближче до 1 — висока видимість,
                        # ближче до 0 — низька.
                        #
                        # round(..., 6) залишає
                        # шість знаків після коми,
                        # щоб JSON не містив надто довгих чисел.
                        landmarks[point.name.lower()] = {
                            "x": round(landmark.x, 6),
                            "y": round(landmark.y, 6),
                            "z": round(landmark.z, 6),
                            "visibility": round(landmark.visibility, 6)
                        }

                    # Записуємо словник усіх 33 точок
                    # у дані поточного кадру.
                    frame_data["landmarks"] = landmarks

                # Додаємо поточний кадр до загального списку.
                #
                # Це відбувається навіть тоді,
                # коли MediaPipe не знайшов людину.
                # Так ми зберігаємо правильні часові позиції.
                frames.append(frame_data)

                # Збільшуємо номер кадру на одиницю.
                # Це аналог:
                # frame_index = frame_index + 1
                frame_index += 1

    finally:
        # Блок finally виконається навіть тоді,
        # коли під час обробки виникне помилка.
        #
        # release() закриває відеофайл
        # і звільняє ресурси OpenCV.
        cap.release()

    # Після обробки всіх кадрів формуємо
    # загальний словник результату.
    #
    # schema_version — версія структури JSON.
    # Корисно для узгодження формату з командою.
    #
    # video — технічна інформація про відео.
    #
    # frames — усі оброблені кадри.
    #
    # overall_score = None:
    # Оцінювання техніки ще не реалізовано.
    #
    # errors = []:
    # Список виявлених технічних помилок
    # поки порожній.
    return {
        "schema_version": "1.0",
        "video": {
            "fps": fps,
            "total_frames": frame_index
        },
        "frames": frames,
        "overall_score": None,
        "errors": []
    }


# Ця умова перевіряє, чи файл запускається напряму.
#
# Якщо ми запускаємо analyzer.py у PyCharm,
# значення __name__ дорівнює "__main__".
#
# Якщо Адріан імпортує функцію analyze_video
# у свій бекенд, цей блок автоматично не виконається.
if __name__ == "__main__":

    # __file__ — шлях до поточного Python-файлу.
    #
    # Path(__file__).parent — папка, де лежить analyzer.py.
    #
    # Оператор / у pathlib з'єднує частини шляху.
    #
    # Тобто ми формуємо шлях до тестового відео
    # незалежно від поточної робочої папки.
    video_path = (
        Path(__file__).parent
        / "Test_video"
        / "video_2026-10-21_23-45-24.mp4"
    )

    # Викликаємо основну функцію аналізу.
    #
    # Вона відкриє відео, обробить кадри
    # та поверне Python-словник із результатами.
    result = analyze_video(video_path)

    # Вказуємо, куди потрібно зберегти JSON.
    # Файл result.json буде створено
    # поруч із analyzer.py.
    output_path = Path(__file__).parent / "result.json"

    # Відкриваємо файл для запису.
    #
    # "w" — режим запису.
    # Якщо файл існує, його вміст буде перезаписано.
    #
    # encoding="utf-8" — підтримка українських символів.
    with open(output_path, "w", encoding="utf-8") as file:

        # Перетворюємо Python-словник у JSON.
        #
        # ensure_ascii=False — зберігаємо Unicode-символи
        # без перетворення на спеціальні escape-послідовності.
        #
        # indent=2 — створюємо відступи для читабельності.
        json.dump(
            result,
            file,
            ensure_ascii=False,
            indent=2
        )

    # Повідомляємо, куди збережено результат.
    print(f"JSON збережено: {output_path}")

    # Виводимо кількість успішно зчитаних кадрів.
    print(
        f"Оброблено кадрів: {result['video']['total_frames']}"
    )
